-- Local Compose credentials only. Production creates these roles using managed secrets.
CREATE ROLE khoj_app LOGIN PASSWORD 'khoj-local-only' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
GRANT CONNECT ON DATABASE khoj TO khoj_app;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO khoj_app;
ALTER DEFAULT PRIVILEGES FOR ROLE khoj IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO khoj_app;
ALTER DEFAULT PRIVILEGES FOR ROLE khoj IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO khoj_app;
